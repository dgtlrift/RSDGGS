"""Generate src/constants.rs: the RSDGGS face centres and pentagon vertices.

    python3 tools/gen_constants.py > src/constants.rs

Standard library only. The orientation is the one in draft section 4.3:

1. The dodecahedron's face centres are the twelve vertices of the unit icosahedron,
   the normalised forms of (0, +-1, +-phi), (+-1, +-phi, 0) and (+-phi, 0, +-1).
   Its vertices are the normalised centroids of the twenty icosahedron triangles.
2. The solid is rotated so that one face centre lies at FACE1 and an adjacent face
   centre lies at bearing FACE2_BEARING from it (adjacent centres are arctan(2),
   about 63.43 degrees, apart). The icosahedral rotation group acts simply
   transitively on ordered pairs of adjacent vertices, so the starting pair does
   not matter.
3. Faces are numbered by LABELS: face k is the face whose centre is nearest the
   approximate centre listed for it. The low two bits of the number are the ITU
   Region of the face's main population (1, 2, 3), or 0 for none.
4. Each face's vertices are ordered counter-clockwise as seen from outside the
   sphere, starting with the vertex at the smallest bearing (clockwise from true
   north) from the face centre. Triangle k of a face is (centre, v[k], v[k+1 mod 5]).
"""

import math

FACE1 = (60.0, 26.5)          # latitude, longitude in degrees
FACE2_BEARING = 304.0         # degrees clockwise from true north, at FACE1

# number: (name, approximate centre (lat, lon))
LABELS = {
    0: ("Antarctica / New Zealand", (-60.0, -154.4)),
    1: ("Europe (R1)", (60.0, 26.5)),
    2: ("North America (R2)", (39.6, -79.1)),
    3: ("Asia (R3)", (23.9, 104.3)),
    4: ("South Atlantic", (-54.8, 1.6)),
    5: ("Africa / Middle East (R1)", (-1.9, 44.6)),
    6: ("South America (R2)", (-23.9, -75.7)),
    7: ("Eastern Australia (R3)", (-6.4, 161.4)),
    8: ("Southern Indian Ocean", (-39.6, 100.9)),
    9: ("West Africa (R1)", (6.4, -18.4)),
    10: ("Central Pacific (R2)", (1.9, -135.4)),
    11: ("North Pacific (R3)", (54.8, -178.5)),
}


def unit(lat, lon):
    la, lo = math.radians(lat), math.radians(lon)
    return (math.cos(la) * math.cos(lo), math.cos(la) * math.sin(lo), math.sin(la))


def latlon(v):
    return math.degrees(math.asin(max(-1.0, min(1.0, v[2])))), math.degrees(math.atan2(v[1], v[0]))


def dot(a, b):
    return sum(x * y for x, y in zip(a, b))


def cross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def norm(v):
    n = math.sqrt(dot(v, v))
    return tuple(x / n for x in v)


def destination(lat, lon, bearing, dist):
    la, lo, b, d = map(math.radians, (lat, lon, bearing, dist))
    la2 = math.asin(math.sin(la) * math.cos(d) + math.cos(la) * math.sin(d) * math.cos(b))
    lo2 = lo + math.atan2(math.sin(b) * math.sin(d) * math.cos(la),
                          math.cos(d) - math.sin(la) * math.sin(la2))
    return math.degrees(la2), math.degrees(lo2)


def bearing(c, v):
    """Bearing of v from c, degrees clockwise from true north, in [0, 360)."""
    north = norm(cross(cross(c, (0.0, 0.0, 1.0)), c))
    east = cross(north, c)
    return math.degrees(math.atan2(dot(v, east), dot(v, north))) % 360.0


def frame(a, b):
    """Orthonormal frame (rows) with a first and b in the first two axes' plane."""
    e2 = norm(tuple(y - dot(a, b) * x for x, y in zip(a, b)))
    return (a, e2, cross(a, e2))


def main():
    phi = (1 + math.sqrt(5)) / 2
    ico = [norm(v) for v in
           [(0, s1, s2 * phi) for s1 in (1, -1) for s2 in (1, -1)]
           + [(s1, s2 * phi, 0) for s1 in (1, -1) for s2 in (1, -1)]
           + [(s1 * phi, 0, s2) for s1 in (1, -1) for s2 in (1, -1)]]
    adj = 1 / math.sqrt(5)                     # cosine of the angle between adjacent centres
    a = ico[0]
    b = next(v for v in ico if abs(dot(a, v) - adj) < 1e-9)
    ta = unit(*FACE1)
    tb = unit(*destination(*FACE1, FACE2_BEARING, math.degrees(math.acos(adj))))
    src, dst = frame(a, b), frame(ta, tb)

    def rotate(v):
        local = [dot(v, e) for e in src]
        return tuple(sum(local[i] * dst[i][j] for i in range(3)) for j in range(3))

    centres = [rotate(v) for v in ico]
    tris = [(i, j, k) for i in range(12) for j in range(i + 1, 12) for k in range(j + 1, 12)
            if all(abs(dot(ico[p], ico[q]) - adj) < 1e-9 for p, q in ((i, j), (j, k), (i, k)))]
    assert len(tris) == 20
    verts = [norm(tuple(sum(centres[i][d] for i in t) for d in range(3))) for t in tris]

    order = []
    for k in range(12):
        hint = unit(*LABELS[k][1])
        best = max(range(12), key=lambda i: dot(centres[i], hint))
        assert math.degrees(math.acos(min(1.0, dot(centres[best], hint)))) < 0.5, k
        order.append(best)
    assert sorted(order) == list(range(12))

    out = ["// Generated by tools/gen_constants.py; do not edit by hand.",
           f"// Orientation (draft section 4.3): Face 1 centre at {FACE1[0]:.1f}N {FACE1[1]:.1f}E,",
           f"// Face 2 centre at bearing {FACE2_BEARING:.1f} degrees from it.",
           "",
           "/// RSDGGS face center unit vectors [x, y, z], indexed by face number 0..11.",
           "#[rustfmt::skip]",
           "pub const FACE_CENTERS: [[f64; 3]; 12] = ["]
    faces = []
    for k, i in enumerate(order):
        c = centres[i]
        mine = sorted((v for v in verts if dot(v, c) > 0.79), key=lambda v: bearing(c, v))
        assert len(mine) == 5
        # Counter-clockwise from outside is decreasing bearing: v0 first, then the rest reversed.
        mine = [mine[0]] + mine[:0:-1]
        faces.append((c, mine))
        la, lo = latlon(c)
        out.append(f"    // F{k:>2} — {LABELS[k][0]:<28} ({la:+.2f}°, {lo:.2f}°)")
        out.append("    [" + ", ".join(f"{x:.18f}" for x in c) + "],")
    out += ["];", "",
            "/// Pentagon vertex unit vectors for each face, 5 vertices per face, counter-clockwise",
            "/// as seen from outside the sphere, starting at the smallest bearing from the centre.",
            "/// pent_verts[face][vertex] = [x, y, z]",
            "#[rustfmt::skip]",
            "pub const FACE_PENTAGON_VERTS: [[[f64; 3]; 5]; 12] = ["]
    for k, (c, mine) in enumerate(faces):
        out.append(f"    // F{k:>2} — {LABELS[k][0]}")
        out.append("    [")
        for n, v in enumerate(mine):
            la, lo = latlon(v)
            out.append("        [" + ", ".join(f"{x:.18f}" for x in v) + f"], // v{n} ({la:+.1f}°,{lo:+.1f}°)")
        out.append("    ],")
    out.append("];")
    print("\n".join(out))


if __name__ == "__main__":
    main()
