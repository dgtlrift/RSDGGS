pub struct Metro {
    pub name: &'static str,
    pub lat: f64,
    pub lon: f64,
    pub pop_millions: f32,
}

pub enum MetroRef {
    Contains { name: &'static str, pop_millions: f32 },
    Within   { name: &'static str, dist_km: f64 },
    Near     { name: &'static str, dist_km: f64 },
}

fn haversine_km(lat1: f64, lon1: f64, lat2: f64, lon2: f64) -> f64 {
    const R: f64 = 6371.0;
    let dlat = (lat2 - lat1).to_radians();
    let dlon = (lon2 - lon1).to_radians();
    let a = (dlat / 2.0).sin().powi(2)
        + lat1.to_radians().cos() * lat2.to_radians().cos() * (dlon / 2.0).sin().powi(2);
    2.0 * R * a.sqrt().asin()
}

fn lon_in_range(lon: f64, lon_min: f64, lon_max: f64) -> bool {
    if lon_min <= lon_max { lon >= lon_min && lon <= lon_max }
    else                  { lon >= lon_min || lon <= lon_max }  // antimeridian crossing
}

/// Find the metro context for a bounding cell.
///
/// Returns `Contains` if a metro centroid falls inside the bbox (largest by population),
/// `Within` if the cell center is within the metro's estimated urban radius,
/// or `Near` with the distance to the nearest metro centroid.
pub fn metro_context(bbox: [f64; 4], clat: f64, clon: f64) -> MetroRef {
    let [lat_min, lat_max, lon_min, lon_max] = bbox;

    let within: Vec<&Metro> = METROS.iter()
        .filter(|m| m.lat >= lat_min && m.lat <= lat_max && lon_in_range(m.lon, lon_min, lon_max))
        .collect();

    if !within.is_empty() {
        let best = within.iter()
            .max_by(|a, b| a.pop_millions.partial_cmp(&b.pop_millions)
                .unwrap_or(std::cmp::Ordering::Equal))
            .unwrap();
        return MetroRef::Contains { name: best.name, pop_millions: best.pop_millions };
    }

    let (nearest, dist_km) = METROS.iter()
        .map(|m| (m, haversine_km(clat, clon, m.lat, m.lon)))
        .min_by(|(_, a), (_, b)| a.partial_cmp(b).unwrap_or(std::cmp::Ordering::Equal))
        .unwrap();

    // Rough urban radius estimate: sqrt(pop_M) * 15 km
    let metro_radius = (nearest.pop_millions as f64).sqrt() * 15.0;
    if dist_km <= metro_radius {
        MetroRef::Within { name: nearest.name, dist_km }
    } else {
        MetroRef::Near { name: nearest.name, dist_km }
    }
}

